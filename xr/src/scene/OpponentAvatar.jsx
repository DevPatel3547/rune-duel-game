import { useRef, useMemo, useEffect } from 'react';
import { useFrame } from '@react-three/fiber';
import * as THREE from 'three';
import { useGame, spellInfo } from '../store.js';
import { mirrorPoint, OPP_DIST } from '../config.js';
import { stoneMaterialMaps, clothMaterialMaps, metalMaterialMaps, glowSprite } from './textures.js';
import { Spring, Spring3, SpringChain, PhaseClip, fbm1, damp, clamp01, easeOutCubic, easeInCubic } from './anim.js';
import GlowTrail from '../draw/GlowTrail.jsx';
import { useWizardModel, poseBone } from './WizardModel.jsx';
import { scannedMaterial } from './materials.js';
import { toonMaterial, addOutline } from './toon.js';

// ============================================================================
// THE OPPONENT — a hooded sorcerer.
//
// The body is now a SKINNED MESH: one continuous surface bound to a 24-bone
// skeleton, generated by tools/build_wizard.py in Blender. Previously it was a
// hierarchy of capsules and spheres, which has a hard ceiling — primitives
// never merge into one surface, so the figure always read as a mannequin
// assembled from parts. A skinned mesh deforms across the joints like skin.
//
// The spring rig below is unchanged and still owns all motion; it simply drives
// real bones now instead of nested groups. Poses are applied as deltas onto
// each bone's captured BIND rotation — assigning rotations directly would
// discard the rest pose and collapse the character.
//
// ANIMATION IS ENTIRELY SPRING-DRIVEN. The previous pass wrote sine waves and
// lerps straight onto joint rotations, which is why it read as robotic: a lerp
// has no momentum, so motion stops dead the moment its target does, and every
// joint arrived at once. Here each joint is a Spring with mass — it overshoots,
// settles, and lags its parent. Combined with SpringChains on the cape and
// hood, that produces follow-through and secondary motion for free.
//
// Casting runs through a PhaseClip: ANTICIPATION (coil back — this is the
// telegraph that lets a player react), STRIKE (fast commit), RECOVERY (settle).
// ============================================================================

const Y180 = new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(0, 1, 0), Math.PI);
const OZ = -OPP_DIST + 0.05;

// Cast timing, in seconds. The anticipation is deliberately long: research on
// combat design is consistent that ENEMY wind-ups should be generous (they are
// the player's cue to react), while player actions stay snappy.
const CAST_PHASES = [['anticipate', 0.42], ['strike', 0.14], ['recover', 0.44]];

// ------------------------------------------------------------- geometry ----

const HOOD_GAP = Math.PI * 0.30;

// ================================================================= avatar ===

export default function OpponentAvatar() {
  const presence = useGame((s) => s.oppPresence);
  const oppTrail = useGame((s) => s.oppTrail);

  // ---- joint refs (the "skeleton") -------------------------------------
  const root = useRef();
  const staffGroup = useRef();
  // Attachment mounts, synced to bone world transforms each frame.
  const staffMount = useRef(), castMount = useRef(), headMount = useRef();
  const crystalMat = useRef(), crystalGlow = useRef();
  const eyeMatL = useRef(), eyeMatR = useRef();
  const eyeL = useRef(), eyeR = useRef();
  const chargeRef = useRef();

  const { scene, bones, bind } = useWizardModel();

  // Re-dress the imported glTF with scanned material. The exporter writes flat
  // Principled values, and the Blender-side material NAME is the contract that
  // says which real material each surface should get — that is why the
  // generator bothers to name them.
  useEffect(() => {
    // CEL SHADED. The scanned colour/normal maps are kept so surface detail
    // still reads, but lighting is quantised into hard bands and every piece
    // gets a rim light — without the rim a dark robe against a dark arena has
    // no silhouette at all, because banded shading provides no gradient to
    // separate them.
    const cloth = scannedMaterial('cloth', { repeat: [3, 3] });
    const leather = scannedMaterial('leather', { repeat: [3, 3] });
    const metalS = scannedMaterial('metal', { repeat: [1, 1] });

    const clothMat = toonMaterial({
      color: '#2a2f45', map: cloth.map, normalMap: cloth.normalMap,
      normalScale: 0.5, rimColor: '#35d6ff', rimPower: 3.2, rimStrength: 0.42,
      stops: [0.34, 0.66], levels: [0.22, 0.66, 1.0],
      side: THREE.DoubleSide,
    });
    // Skin: fewer, softer bands than cloth. Anime faces are shaded with one
    // broad shadow shape, not a stack of steps.
    const skinMat = toonMaterial({
      color: '#c9a292', map: leather.map, normalMap: leather.normalMap,
      normalScale: 0.22, rimColor: '#9ce8ff', rimPower: 3.4, rimStrength: 0.30,
      stops: [0.5], levels: [0.55, 1.0],
    });
    const metalMat = toonMaterial({
      color: '#7f8aa6', map: metalS.map, normalMap: metalS.normalMap,
      normalScale: 0.55, rimColor: '#8af0ff', rimPower: 2.2, rimStrength: 0.75,
      stops: [0.42, 0.72], levels: [0.24, 0.72, 1.0],
    });

    scene.traverse((o) => {
      if (!o.isMesh && !o.isSkinnedMesh) return;
      const name = o.material?.name || '';
      // aoMap samples uv2; the glTF only carries uv.
      const g = o.geometry;
      if (g?.attributes.uv && !g.attributes.uv2) g.setAttribute('uv2', g.attributes.uv);

      if (/metal/i.test(name)) o.material = metalMat;
      else if (/cloth/i.test(name)) o.material = clothMat;
      else o.material = skinMat;      // the MakeHuman body itself
    });

    // Inverted-hull outline. Added once, after materials, so the shells copy
    // the final mesh set.
    if (!scene.userData.outlined) {
      scene.userData.outlined = true;
      addOutline(scene, { thickness: 0.0035, color: '#05060a' });
    }
  }, [scene]);

  const trimMaps = metalMaterialMaps();
  const stoneMaps = stoneMaterialMaps();


  // ---- the animation rig ------------------------------------------------
  // One Spring per animated degree of freedom. Stiffness/damping are chosen
  // per joint by how heavy that body part should feel: the pelvis is slow and
  // heavy, the head is light and quick, the staff tip whips.
  const rig = useMemo(() => ({
    seed: Math.random() * 100,

    rootY: new Spring(0, 70, 16),
    rootPitch: new Spring(0, 60, 15),

    pelvisX: new Spring(0, 55, 13),        // weight shift
    pelvisYaw: new Spring(0, 45, 12),
    pelvisRoll: new Spring(0, 55, 13),

    spinePitch: new Spring(0.02, 90, 15),  // under-damped: recoils on a hit
    spineRoll: new Spring(0, 80, 16),
    chestYaw: new Spring(0, 70, 15),

    neckPitch: new Spring(0, 130, 17),
    headYaw: new Spring(0, 110, 16),       // lags the chest → head-lead/lag
    headPitch: new Spring(0.06, 110, 16),
    headRoll: new Spring(0, 100, 15),

    shoulderR: new Spring3(-0.22, 0, -0.26, 95, 16),
    elbowR: new Spring(-0.42, 110, 17),
    shoulderL: new Spring3(-0.18, 0, 0.30, 95, 16),
    elbowL: new Spring(-0.38, 110, 17),

    hipL: new Spring(0, 60, 14), hipR: new Spring(0, 60, 14),
    kneeL: new Spring(0, 70, 15), kneeR: new Spring(0, 70, 15),

    staffPitch: new Spring(-0.04, 80, 13), // loose: the staff swings
    staffRoll: new Spring(-0.03, 80, 13),

    cape: new SpringChain(3, 70, 12, 0.72),
    hoodSway: new SpringChain(2, 95, 14, 0.8),

    charge: new Spring(0, 120, 22),        // 0..1 energy gathering in the hand
    eye: new Spring(1, 90, 18),
    handCurl: new Spring(0.3, 130, 20),    // free hand opens to release
    // Footwork: a real person standing does not hold one pose. They shift
    // weight between feet every few seconds, and the unweighted foot lifts
    // slightly. `weight` is -1 (all on their left) .. +1 (all on their right).
    weight: new Spring(0, 22, 8.5),
    nextShift: 2 + Math.random() * 3,
    // Blinks are the cheapest possible signal that something is alive.
    blink: 0,
    nextBlink: 1 + Math.random() * 3,
    // Between casts the wizard settles into a guard, then loosens. Purely
    // decorative, but a body that only moves when it attacks reads as a prop.
    guard: new Spring(0, 30, 10),
    // a heavy hit shoves the whole body back a step, and it recovers its mark
    knock: new Spring(0, 55, 9),
    nextGuard: 3 + Math.random() * 4,

    castClip: new PhaseClip(CAST_PHASES),
    wasCasting: false,
    lastHp: 100,
    deathT: 0,
  }), []);

  // React to damage imperatively: an impulse into the springs, so a hit
  // physically rocks the body and it settles, rather than a scalar that decays.
  useEffect(() => useGame.subscribe((s) => {
    const hp = s.hp.opponent;
    if (hp < rig.lastHp) {
      const mag = clamp01((rig.lastHp - hp) / 26);
      rig.spinePitch.impulse(-5.5 * mag);
      rig.neckPitch.impulse(-7 * mag);
      rig.headRoll.impulse((Math.random() - 0.5) * 6 * mag);
      rig.rootPitch.impulse(-2.2 * mag);
      rig.pelvisX.impulse((Math.random() - 0.5) * 1.4 * mag);
      rig.shoulderR.x.impulse(3.2 * mag);
      rig.shoulderL.x.impulse(3.0 * mag);
      rig.cape.impulse(-6 * mag, 0);
      rig.hoodSway.impulse(-5 * mag, 0);
      rig.staffPitch.impulse(4 * mag);
      // Chip damage only flinches; a real hit moves them. Stagger is what makes
      // a big spell read as big on the body it lands on.
      if (mag > 0.35) rig.knock.impulse(-3.4 * mag);
    }
    rig.lastHp = hp;
  }), [rig]);

  useFrame((state, rawDt) => {
    const dt = Math.min(0.05, rawDt);
    const t = state.clock.elapsedTime;
    const g = useGame.getState();
    const casting = !!oppTrail?.active;

    // ---- trigger the cast clip on the rising edge ---------------------
    if (casting && !rig.wasCasting) rig.castClip.play();
    rig.wasCasting = casting;
    rig.castClip.update(dt);
    const { phase, p } = rig.castClip.state;

    // ---- death ---------------------------------------------------------
    const dying = g.phase === 'over' && g.hp.opponent <= 0;
    rig.deathT = damp(rig.deathT, dying ? 1 : 0, 3.0, dt);
    const death = easeInCubic(rig.deathT);

    // ---- idle: wandering noise, not a loopable sine --------------------
    const n = rig.seed;
    const sway = fbm1(t * 0.22 + n);              // slow weight drift
    const sway2 = fbm1(t * 0.31 + n + 40);
    const breath = Math.sin(t * 1.15 + n) * 0.5 + 0.5;
    const micro = fbm1(t * 1.7 + n + 80) * 0.35;  // small settling adjustments

    // ---- weight shifts: pick a new foot every few seconds ---------------
    rig.nextShift -= dt;
    if (rig.nextShift <= 0) {
      rig.weight.to(rig.weight.target > 0 ? -0.6 - Math.random() * 0.4 : 0.6 + Math.random() * 0.4);
      rig.nextShift = 2.6 + Math.random() * 3.4;
    }
    const W = rig.weight.update(dt);

    // ---- blinks ---------------------------------------------------------
    rig.nextBlink -= dt;
    if (rig.nextBlink <= 0) { rig.blink = 1; rig.nextBlink = 1.6 + Math.random() * 4.2; }
    // a blink is ~120 ms; decay fast so it reads as a snap, not a fade
    rig.blink = Math.max(0, rig.blink - dt * 8.5);

    // ---- idle guard: settle into a stance between casts ------------------
    rig.nextGuard -= dt;
    if (rig.nextGuard <= 0) {
      rig.guard.to(rig.guard.target > 0.5 ? 0 : 1);
      rig.nextGuard = 3.5 + Math.random() * 4.5;
    }
    const guard = rig.guard.update(dt);

    // ---- cast pose targets ---------------------------------------------
    // anticipation coils AWAY from the player (the classic wind-up), the
    // strike fires forward past neutral, recovery settles back.
    let coil = 0, thrust = 0;
    if (phase === 'anticipate') coil = easeOutCubic(p);
    else if (phase === 'strike') { coil = 1 - p; thrust = easeOutCubic(p); }
    else if (phase === 'recover') { thrust = 1 - easeOutCubic(p); }
    const commit = thrust - coil * 0.55;   // −0.55…1 : back on wind-up, forward on release

    // charge builds through the anticipation and dumps on the strike
    rig.charge.to(phase === 'anticipate' ? p : phase === 'strike' ? 1 - p : 0);

    // ---- drive the targets ---------------------------------------------
    rig.rootY.to(-death * 0.62);
    rig.rootPitch.to(death * 1.2);

    // hips travel toward whichever foot carries the weight, and drop on that
    // side — the pelvic tilt is what actually sells a weight shift
    rig.pelvisX.to(sway * 0.04 + W * 0.055);
    rig.pelvisYaw.to(sway2 * 0.11 + commit * 0.10 - W * 0.06);
    rig.pelvisRoll.to(-sway * 0.05 - W * 0.075);

    rig.spinePitch.to(0.02 + breath * 0.022 - coil * 0.16 + thrust * 0.30);
    // counter-lean so the head stays over the base of support
    rig.spineRoll.to(sway * 0.035 + W * 0.05);
    rig.chestYaw.to(-sway2 * 0.08 + commit * 0.16);

    rig.neckPitch.to(coil * 0.14 - thrust * 0.20);
    // the head keeps looking at the player through the whole action —
    // counter-rotating against the chest is what makes a body read as aiming
    // counter-rotate against the chest so the gaze stays locked on the player
    // through the whole action — that is what reads as 'aiming at you'
    rig.headYaw.to(sway2 * 0.09 - rig.chestYaw.value * 0.8 - W * 0.04);
    rig.headPitch.to(0.06 + micro * 0.05 - thrust * 0.10);
    rig.headRoll.to(sway * 0.05);

    // Staff arm: a small upper-arm lift, most of the motion in the elbow. The
    // staff itself carries the read, so the arm does not need to travel far.
    rig.shoulderR.to(-0.22 - coil * 0.30 + thrust * 0.16, 0, -0.26 - coil * 0.10);
    rig.elbowR.to(-0.42 - coil * 0.34 + thrust * 0.20);
    // Free hand: gathers energy at the chest, then extends toward the player.
    // This is the arm that sells the cast, so it gets the larger range.
    rig.shoulderL.to(-0.18 - coil * 0.22 - thrust * 0.72 + micro * 0.04, 0, 0.30 - thrust * 0.14);
    rig.elbowL.to(-0.38 - coil * 0.50 + thrust * 0.42);

    // legs: a braced stance that digs in as the cast commits
    // The unweighted leg bends more and its hip swings slightly forward; the
    // weighted leg straightens to carry the load. Guard widens the stance.
    const offL = THREE.MathUtils.clamp(W, 0, 1);        // weight off the left
    const offR = THREE.MathUtils.clamp(-W, 0, 1);
    rig.hipL.to(0.05 + sway * 0.04 - commit * 0.10 + offL * 0.16 - guard * 0.10);
    rig.hipR.to(-0.04 - sway * 0.04 + commit * 0.14 + offR * 0.16 + guard * 0.06);
    rig.kneeL.to(0.08 + coil * 0.12 + offL * 0.22 + guard * 0.14);
    rig.kneeR.to(0.07 + coil * 0.16 + offR * 0.22 + guard * 0.14);

    rig.staffPitch.to(-0.04 - coil * 0.22 + thrust * 0.30);
    rig.staffRoll.to(-0.03 + sway * 0.05);

    rig.eye.to(casting ? 2.6 : 1.0 + micro * 0.2);
    // fist while gathering, flung open on the strike
    rig.handCurl.to(phase === 'anticipate' ? 0.30 + p * 0.55 : phase === 'strike' ? 0.05 : 0.30);

    // ---- integrate -------------------------------------------------------
    rig.rootY.update(dt); rig.rootPitch.update(dt);
    rig.pelvisX.update(dt); rig.pelvisYaw.update(dt); rig.pelvisRoll.update(dt);
    rig.spinePitch.update(dt); rig.spineRoll.update(dt); rig.chestYaw.update(dt);
    rig.neckPitch.update(dt); rig.headYaw.update(dt); rig.headPitch.update(dt); rig.headRoll.update(dt);
    rig.shoulderR.update(dt); rig.elbowR.update(dt);
    rig.shoulderL.update(dt); rig.elbowL.update(dt);
    rig.hipL.update(dt); rig.hipR.update(dt); rig.kneeL.update(dt); rig.kneeR.update(dt);
    rig.staffPitch.update(dt); rig.staffRoll.update(dt);
    rig.knock.update(dt);
    rig.charge.update(dt); rig.eye.update(dt); rig.handCurl.update(dt);

    // secondary motion: the cape and hood follow the CHEST's actual motion, so
    // they whip when the body lunges and trail when it stops

    // ---- apply to the SKELETON -------------------------------------------
    // Every pose is a delta on the bind rotation; see WizardModel.jsx.
    if (root.current) {
      root.current.position.y = rig.rootY.value;
      root.current.position.z = OZ + rig.knock.value;
      root.current.rotation.x = rig.rootPitch.value;
    }
    // ---- bone name mapping ------------------------------------------------
    // The character is now the MakeHuman base mesh (via MPFB2), whose skeleton
    // is anatomical rather than minimal: a five-segment spine, a three-segment
    // neck, split upper/lower arm bones. Spreading a pose across several
    // segments is also what makes it read as a spine bending rather than a
    // hinge opening.
    const B = bones;
    const b = (n) => B[n];
    // Weight shift is expressed as hip rotation only. Translating a bone of a
    // skinned mesh drags the vertices bound to it away from their neighbours
    // and tears the surface; the lateral sway lives on `root` instead.
    poseBone(b('root'), bind.get('root'), 0, rig.pelvisYaw.value, rig.pelvisRoll.value);
    // An online opponent strafes too. Their x is in their own frame, so it is
    // mirrored here; damped so 22 Hz presence updates read as a smooth step.
    rig.lateral = damp(rig.lateral ?? 0, -(g.oppX || 0), 9, dt);
    if (root.current) root.current.position.x = rig.pelvisX.value + rig.lateral;
    // Spine: distribute the bend across all five segments.
    const spineSegs = ['spine05', 'spine04', 'spine03', 'spine02', 'spine01'];
    spineSegs.forEach((n, i) => {
      const w = [0.30, 0.26, 0.20, 0.14, 0.10][i];
      poseBone(b(n), bind.get(n), rig.spinePitch.value * w * 5 * 0.34,
               rig.chestYaw.value * w * 5 * 0.22 + breath * 0.004,
               rig.spineRoll.value * w * 5 * 0.30);
    });
    ['neck01', 'neck02', 'neck03'].forEach((n) => {
      poseBone(b(n), bind.get(n), rig.neckPitch.value * 0.34, 0, 0);
    });
    if (!presence) {
      poseBone(b('head'), bind.get('head'), rig.headPitch.value, rig.headYaw.value, rig.headRoll.value);
    }

    // Arms. The skeleton's rest pose has them hanging down the sides, so the
    // rig's shoulder angles map straight onto the upper-arm bones.
    // Arms. The base mesh stands in an A-pose with the arms already out and
    // down, so these are deltas ON that rest pose, not absolute angles.
    [['L', rig.shoulderL, rig.elbowL], ['R', rig.shoulderR, rig.elbowR]].forEach(([sd, sh, el]) => {
      poseBone(b(`clavicle.${sd}`), bind.get(`clavicle.${sd}`), sh.x.value * 0.18, 0, 0);
      poseBone(b(`upperarm01.${sd}`), bind.get(`upperarm01.${sd}`), sh.x.value * 0.6, 0, sh.z.value * 0.5);
      poseBone(b(`upperarm02.${sd}`), bind.get(`upperarm02.${sd}`), sh.x.value * 0.4, 0, 0);
      poseBone(b(`lowerarm01.${sd}`), bind.get(`lowerarm01.${sd}`), el.value * 0.6, 0, 0);
      poseBone(b(`lowerarm02.${sd}`), bind.get(`lowerarm02.${sd}`), el.value * 0.4, 0, 0);
    });
    poseBone(b('wrist.L'), bind.get('wrist.L'), -rig.handCurl.value * 0.5, 0, 0);
    poseBone(b('wrist.R'), bind.get('wrist.R'), -0.35, 0, 0);

    [['L', rig.hipL, rig.kneeL], ['R', rig.hipR, rig.kneeR]].forEach(([sd, hip, knee]) => {
      poseBone(b(`upperleg01.${sd}`), bind.get(`upperleg01.${sd}`), hip.value * 0.7, 0, 0);
      poseBone(b(`upperleg02.${sd}`), bind.get(`upperleg02.${sd}`), hip.value * 0.3, 0, 0);
      poseBone(b(`lowerleg01.${sd}`), bind.get(`lowerleg01.${sd}`), knee.value * 0.6, 0, 0);
      poseBone(b(`lowerleg02.${sd}`), bind.get(`lowerleg02.${sd}`), knee.value * 0.4, 0, 0);
    });

    if (staffGroup.current) {
      staffGroup.current.rotation.x = rig.staffPitch.value;
      staffGroup.current.rotation.z = rig.staffRoll.value;
    }

    // ---- keep attachments glued to their bones ---------------------------
    // glTF has no socket concept, so each mount copies a bone's world
    // transform. Done after posing so it uses this frame's pose, not last
    // frame's.
    if (b('wrist.L') && castMount.current) syncToBone(castMount.current, b('wrist.L'), root.current);
    if (b('head') && headMount.current) syncToBone(headMount.current, b('head'), root.current, HEAD_OFFSET);

    // charge orb in the free hand
    if (chargeRef.current) {
      const c = rig.charge.value;
      chargeRef.current.scale.setScalar(0.06 + c * 0.34);
      chargeRef.current.material.opacity = Math.min(1, c * 1.2);
      chargeRef.current.visible = c > 0.01;
    }

    // staff crystal: bright through the wind-up, flares on release
    if (crystalMat.current) {
      const target = 1.4 + rig.charge.value * 4.5 + (phase === 'strike' ? 4 : 0);
      crystalMat.current.emissiveIntensity = damp(crystalMat.current.emissiveIntensity, target, 12, dt);
    }
    if (crystalGlow.current) crystalGlow.current.scale.setScalar(0.3 + rig.charge.value * 0.35);

    const eg = rig.eye.value * (1 - rig.deathT * 0.95);
    [eyeMatL.current, eyeMatR.current].forEach((m) => {
      if (m) m.color.setRGB(0.66 * eg, 0.96 * eg, 1.0 * eg);
    });
    [eyeL.current, eyeR.current].forEach((m) => {
      if (m) m.scale.y = Math.max(0.04, 1 - rig.blink);
    });

    // ---- online presence overrides the idle head/hands ------------------
    if (presence && bones.head && presence.head) {
      // Online: aim the head bone at the mirrored real head direction. Only
      // rotation is driven — translating a bone would tear the skinned mesh.
      TMPQ.fromArray(presence.head.q).premultiply(Y180);
      bones.head.quaternion.copy(bind.get('head') || IDENT).multiply(TMPQ);
    }
  });

  const trailPoints = useMemo(() => {
    if (!oppTrail?.points?.length) return [];
    return oppTrail.points.map(mirrorPoint);
  }, [oppTrail]);
  const trailColor = (oppTrail?.spellId && spellInfo(oppTrail.spellId)?.color) || '#cdebff';

  return (
    <group ref={root} position={[0, 0, OZ]}>
      {/* the skinned character; every bone is posed from the rig each frame */}
      <primitive object={scene} />

      {/* Attachments ride the skeleton by being parented to a group that is
          kept in sync with a bone's world transform each frame — glTF gives us
          bones, not sockets. */}
      {/* The staff is anchored in CHARACTER space rather than tracked to the
          hand bone. Bone-tracking it was landing it a metre low and, at a 9 m
          duelling distance, an imperfect grip is invisible while a missing
          staff is not. It still animates: staffGroup is spring-driven, so it
          rakes back on the wind-up and drives forward on the release. */}
      <group ref={staffMount} position={[-0.30, 0.95, 0.06]}>
        <group>
          <group ref={staffGroup}>
          <mesh position={[0, 0.42, 0]} castShadow>
            <cylinderGeometry args={[0.019, 0.026, 1.85, 8]} />
            <meshStandardMaterial {...stoneMaps} color="#4a3324" roughness={0.65} metalness={0.25} envMapIntensity={0.6} />
          </mesh>
          {[0.02, 0.22, 1.14].map((y) => (
            <mesh key={y} position={[0, y + 0.42, 0]} rotation={[Math.PI / 2, 0, 0]}>
              <torusGeometry args={[0.028, 0.008, 6, 16]} />
              <meshStandardMaterial {...trimMaps} color="#9c7f4c" roughness={0.4} metalness={0.92} envMapIntensity={1.3} />
            </mesh>
          ))}
          {[0, 1, 2].map((i) => (
            <mesh key={i} position={[Math.cos((i / 3) * Math.PI * 2) * 0.05, 1.32, Math.sin((i / 3) * Math.PI * 2) * 0.05]} rotation={[0, 0, Math.cos((i / 3) * Math.PI * 2) * -0.4]}>
              <coneGeometry args={[0.018, 0.16, 6]} />
              <meshStandardMaterial {...trimMaps} color="#a88a52" roughness={0.4} metalness={0.92} envMapIntensity={1.3} />
            </mesh>
          ))}
          <mesh position={[0, 1.44, 0]} castShadow>
            <octahedronGeometry args={[0.105, 0]} />
            <meshStandardMaterial
              ref={crystalMat} color="#dcc4ff" emissive="#a86cff" emissiveIntensity={1.5}
              roughness={0.08} metalness={0.2} toneMapped={false}
            />
          </mesh>
          <sprite ref={crystalGlow} position={[0, 1.44, 0]} scale={0.32}>
            <spriteMaterial map={glowSprite()} color="#b98cff" transparent opacity={0.85} blending={THREE.AdditiveBlending} depthWrite={false} toneMapped={false} />
          </sprite>
            <pointLight position={[0, 1.44, 0]} color="#b06cff" intensity={3.2} distance={4.5} decay={2} />
          </group>
        </group>
      </group>

      {/* energy gathering in the free hand during a wind-up */}
      <group ref={castMount}>
        <sprite ref={chargeRef} scale={0.06}>
          <spriteMaterial
            map={glowSprite()} color="#c9a3ff" transparent opacity={0}
            blending={THREE.AdditiveBlending} depthWrite={false} toneMapped={false}
          />
        </sprite>
      </group>

      {/* face: eyes and their glow, pinned to the head bone */}
      <group ref={headMount}>
        {[-1, 1].map((sd) => (
          <mesh key={sd} ref={sd < 0 ? eyeL : eyeR} position={[sd * 0.032, 0.005, 0.078]} rotation={[0, sd * 0.20, sd * 0.42]}>
            <planeGeometry args={[0.046, 0.013]} />
            <meshBasicMaterial
              ref={sd < 0 ? eyeMatL : eyeMatR}
              color="#a9f4ff" toneMapped={false} transparent opacity={1} depthWrite={false} depthTest={false}
            />
          </mesh>
        ))}
        <sprite position={[0, 0.005, 0.07]} scale={[0.19, 0.09, 1]}>
          <spriteMaterial map={glowSprite()} color="#5fd8ff" transparent opacity={0.5} blending={THREE.AdditiveBlending} depthWrite={false} toneMapped={false} />
        </sprite>
        <pointLight position={[0, 0.01, 0.10]} color="#7fe9ff" intensity={1.4} distance={0.9} decay={2} />
      </group>

      {/* contact shadow — plants the figure on the dais */}
      <mesh position={[0, 0.03, 0.02]} rotation={[-Math.PI / 2, 0, 0]} renderOrder={-1}>
        <circleGeometry args={[0.62, 32]} />
        <meshBasicMaterial
          map={glowSprite()} color="#000000" transparent opacity={0.34}
          blending={THREE.MultiplyBlending} depthWrite={false}
        />
      </mesh>

      {trailPoints.length > 0 && (
        <group position={[0, 0, -OZ]}>
          <GlowTrail points={trailPoints} color={trailColor} size={0.055} />
        </group>
      )}
    </group>
  );
}


