// Copy a bone's world transform onto a group that lives under `parent`.
// glTF exposes bones but no attachment sockets, so anything worn or held has to
// be re-anchored every frame after the skeleton is posed.
function syncToBone(target, bone, parent, offset, positionOnly) {
  bone.updateWorldMatrix(true, false);
  bone.matrixWorld.decompose(TMP, TMPQ, TMPS);
  target.position.copy(TMP);
  if (!positionOnly) target.quaternion.copy(TMPQ);
  if (offset) target.position.add(TMP2.copy(offset).applyQuaternion(TMPQ));
  if (parent) {
    parent.updateWorldMatrix(true, false);
    target.position.copy(parent.worldToLocal(target.position));
  }
}
